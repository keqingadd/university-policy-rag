"""查询改写：把口语/简写映射成政策术语，弥补关键词检索的用词差异。

政策问答里用户常说“评贫困生”“国奖”“一年多少钱”，而原文是
“家庭经济困难学生认定”“国家奖学金”“每生每年 1 万元”。这里维护一张
领域同义词表（key -> 规范表述列表），查询时把命中的规范表述追加进检索文本。
"""
from __future__ import annotations

SYNONYMS: dict[str, list[str]] = {
    # 资助 / 认定
    "评贫困生": ["家庭经济困难学生认定"],
    "贫困生": ["家庭经济困难学生"],
    "困难生": ["家庭经济困难学生"],
    "困难认定": ["家庭经济困难学生认定"],
    "评助学金": ["国家助学金"],
    "助学金": ["国家助学金"],
    "国奖": ["国家奖学金"],
    "国励": ["国家励志奖学金"],
    "励志奖学金": ["国家励志奖学金"],
    "励志": ["国家励志奖学金"],
    "助学贷款": ["国家助学贷款"],
    "贷款": ["国家助学贷款"],
    "打工": ["勤工助学"],
    "勤工": ["勤工助学"],
    "工时": ["工时", "小时"],
    # 金额 / 名额类口语（用“每生每年/名额/万元”这些原文里真实出现的词）
    "一年多少钱": ["每生每年", "金额", "万元"],
    "能拿多少钱": ["每生每年", "金额", "万元"],
    "多少钱": ["金额", "万元"],
    "多少个名额": ["名额", "人数"],
    "多少人能拿": ["名额"],
    "多少人": ["名额"],
    "金额": ["金额"],
    # 学籍 / 管理
    "处分": ["纪律处分"],
    "开除": ["开除学籍"],
    "申诉": ["学生申诉"],
    "转专业": ["转专业"],
    # 频率 / 时间类口语
    "多久评一次": ["每学年进行一次"],
    "多久评": ["每学年进行一次"],
    "多久一次": ["每学年"],
    "多长时间": ["期限"],
    "几个工作日": ["工作日"],
}


def expand(text: str) -> str:
    """返回“原查询 + 命中的规范表述”，去重且保持可解释。"""
    extra: list[str] = []
    for key, canonicals in SYNONYMS.items():
        if key in text:
            for canonical in canonicals:
                if canonical not in text:
                    extra.append(canonical)
    if not extra:
        return text
    return text + " " + " ".join(dict.fromkeys(extra))
